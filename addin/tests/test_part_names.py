"""부품 이름이 재계산으로 인스턴스 번호가 바뀌어도 그대로인지 본다(ADR-0006, 티켓 26 2절 선반 업로드).

실물 선반에서 패턴이 만든 오커런스가 재계산마다 `구성요소1:12` → `구성요소1:16`으로 다시 만들어졌고,
어댑터가 인스턴스 번호가 든 전체 경로를 부품 이름으로 써서 모든 스윕 범위가 폭 0으로 줄었다.
"""

from uploader.part_names import stable_part_names


def test_인스턴스_번호가_바뀌어도_같은_위치의_부품은_같은_이름이다() -> None:
    before = stable_part_names([("측판:1", (0.0, 0.0, 0.0)), ("측판:12", (10.0, 0.0, 0.0))])
    after = stable_part_names([("측판:1", (0.0, 0.0, 0.0)), ("측판:16", (10.0, 0.0, 0.0))])

    assert before == after == ["측판#1", "측판#2"]


def test_순번은_목록_순서가_아니라_위치_순서다() -> None:
    assert stable_part_names([("측판:3", (20.0, 0.0, 0.0)), ("측판:1", (0.0, 0.0, 0.0))]) == ["측판#2", "측판#1"]


def test_x가_같으면_y_z_순으로_순번을_정한다() -> None:
    names = stable_part_names([("판:5", (0.0, 5.0, 0.0)), ("판:2", (0.0, 1.0, 9.0)), ("판:9", (0.0, 1.0, 3.0))])

    assert names == ["판#3", "판#2", "판#1"]


def test_다른_컴포넌트끼리는_순번을_섞지_않는다() -> None:
    names = stable_part_names([("상판:1", (0.0, 0.0, 0.0)), ("측판:1", (5.0, 0.0, 0.0)), ("측판:2", (9.0, 0.0, 0.0))])

    assert names == ["상판#1", "측판#1", "측판#2"]


def test_하위_어셈블리_경로는_단계마다_번호를_떼고_이어_붙인다() -> None:
    assert stable_part_names([("선반:1+측판:7", (0.0, 0.0, 0.0))]) == ["선반+측판#1"]


def test_거울_복사본_이름의_괄호는_그대로_둔다() -> None:
    assert stable_part_names([("측판(미러):1", (0.0, 0.0, 0.0))]) == ["측판(미러)#1"]


def test_부동소수_잡음만큼_다른_위치는_같은_위치로_본다() -> None:
    names = stable_part_names([("판:1", (10.0, 0.0, 0.0)), ("판:2", (10.0 + 1e-9, -1.0, 0.0))])

    assert names == ["판#2", "판#1"]
